"""Render results.json into the generated section of RESULTS.md.

Only the text between the two markers is rewritten; the methodology and the
"where appsec-compose is weak" analysis around it are written by hand, because
they interpret the numbers and should be re-read whenever the numbers move.
"""
from __future__ import annotations

from pathlib import Path

BEGIN = "<!-- results:begin (generated by benchmark/bench.py — do not edit by hand) -->"
END = "<!-- results:end -->"

SAST_NAMES = {
    "cmdi": "Command injection", "crypto": "Weak cipher", "hash": "Weak hash",
    "ldapi": "LDAP injection", "pathtraver": "Path traversal",
    "securecookie": "Insecure cookie", "sqli": "SQL injection",
    "trustbound": "Trust boundary", "weakrand": "Weak randomness",
    "xpathi": "XPath injection", "xss": "Cross-site scripting",
}


def pct(v) -> str:
    return "—" if v is None else f"{v * 100:.1f}%"


def signed(v) -> str:
    return "—" if v is None else f"{v * 100:+.1f}"


def headline(suite: str, s: dict) -> str:
    if suite == "sast":
        a = s["average"]
        return f"avg TPR {pct(a['tpr'])}, FPR {pct(a['fpr'])}, score {signed(a['score'])}"
    if suite == "secrets":
        m = s["merged"]
        return f"recall {pct(m['recall'])} ({m['tp']}/{m['tp'] + m['fn']}), precision {pct(m['precision'])}"
    if suite == "sca":
        return f"recall {pct(s['recall'])} ({s['detected']}/{s['expected']})"
    return ""


def _table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" if i == 0 else "--:" for i in range(len(header))) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def _sast(suite: dict) -> list[str]:
    c, runs = suite["corpus"], suite["runs"]
    out = ["### SAST — OWASP Benchmark for Java 1.2", "",
           f"Corpus: [{c['repo'].removeprefix('https://github.com/')}]({c['repo']}) at "
           f"`{c['commit']}` (tree sha256 `{c['tree_sha256'][:16]}…`), "
           f"{next(iter(runs.values()))['score']['test_cases']} test cases.", ""]
    rows = []
    for name, r in runs.items():
        s = r["score"]
        rows.append([r["label"], s.get("rules", "?"), pct(s["average"]["tpr"]),
                     pct(s["average"]["fpr"]), f"**{signed(s['average']['score'])}**",
                     pct(s["totals"]["precision"]), f"{r['runtime_seconds']:.0f} s"])
    out += _table(["Profile", "Rules loaded", "Avg TPR", "Avg FPR", "Benchmark score",
                   "Precision (all cases)", "Runtime"], rows)
    for name, r in runs.items():
        s = r["score"]
        out += ["", f"**{r['label']}** — per category:", ""]
        rows = []
        for cat, v in s["categories"].items():
            rows.append([f"{SAST_NAMES.get(cat, cat)} (CWE-{v['cwe']})", v["tp"], v["fn"],
                         v["fp"], v["tn"], pct(v["tpr"]), pct(v["fpr"]), signed(v["score"])])
        t = s["totals"]
        rows.append(["**All (micro)**", t["tp"], t["fn"], t["fp"], t["tn"], pct(t["tpr"]),
                     pct(t["fpr"]), signed(t["tpr"] - t["fpr"])])
        out += _table(["Category", "TP", "FN", "FP", "TN", "TPR", "FPR", "Score"], rows)
        sev = ", ".join(f"{k} {v}" for k, v in s.get("sast_findings_by_severity", {}).items())
        out += ["", f"SAST findings in the whole report: {s.get('sast_findings')} (by severity: {sev})."]
    return out


def _secrets(suite: dict) -> list[str]:
    c, runs = suite["corpus"], suite["runs"]
    out = ["### Secrets — synthetic labelled corpus (SYNTHETIC)", "",
           f"Corpus: `benchmark/synthetic_secrets.py` v{c['generator_version']}, seed {c['seed']}: "
           f"{c['files']} files, {c['secrets']} labelled secrets, {c['decoys']} decoys "
           f"(tree sha256 `{c['tree_sha256'][:16]}…`).", ""]
    rows = []
    for name, r in runs.items():
        s = r["score"]
        for tool, v in [("merged", s["merged"]), *s["per_tool"].items()]:
            rows.append([r["label"] if tool == "merged" else f"↳ {tool} alone",
                         f"{pct(v['recall'])} ({v['tp']}/{v['tp'] + v['fn']})",
                         pct(v["precision"]), f"{v['fp_decoy']}/{v['fp_decoy'] + v['tn']}",
                         v["fp_unlabeled"],
                         f"{r['runtime_seconds']:.0f} s" if tool == "merged" else ""])
        stray = s.get("trivy_secrets_filed_as_sca")
        if stray:
            rows.append(["↳ trivy secrets (filed under `sca`, not counted above)",
                         f"{pct(stray['recall'])} ({stray['tp']}/{stray['tp'] + stray['fn']})",
                         pct(stray["precision"]), f"{stray['fp_decoy']}/{stray['fp_decoy'] + stray['tn']}",
                         stray["fp_unlabeled"], ""])
    out += _table(["Profile", "Recall", "Precision", "Decoys flagged", "Unlabelled FPs", "Runtime"], rows)

    names = list(runs)
    kinds = runs[names[0]]["score"]["merged"]["by_kind"]
    rows = []
    for kind, v in kinds.items():
        cells = []
        for n in names:
            k = runs[n]["score"]["merged"]["by_kind"][kind]
            cells.append(f"{k['hit']}/{k['total']}")
        rows.append([kind, v["label"], *cells])
    out += ["", "Detected per kind (a decoy \"detected\" is a false positive):", ""]
    out += _table(["Kind", "Label", *[runs[n]["label"] for n in names]], rows)
    return out


def _sca(suite: dict) -> list[str]:
    c, runs = suite["corpus"], suite["runs"]
    out = ["### SCA — pinned vulnerable packages vs. OSV", "",
           f"Corpus: {c['packages']} packages pinned in {', '.join(f'`{m}`' for m in c['manifests'])} "
           f"(tree sha256 `{c['tree_sha256'][:16]}…`). Truth: OSV snapshot taken {c['osv_snapshot']}.", ""]
    names = list(runs)
    ecos = runs[names[0]]["score"]["ecosystems"]
    rows = []
    for eco, v in ecos.items():
        cells = []
        for n in names:
            e = runs[n]["score"]["ecosystems"][eco]
            cells.append(f"{pct(e['recall'])} ({e['detected']}/{e['expected']})")
        rows.append([eco, v["packages"], *cells])
    rows.append(["**All**", sum(v["packages"] for v in ecos.values()),
                 *[f"**{pct(runs[n]['score']['recall'])}** ({runs[n]['score']['detected']}/"
                   f"{runs[n]['score']['expected']})" for n in names]])
    out += _table(["Ecosystem", "Packages", *[runs[n]["label"] for n in names]], rows)
    out += [""]
    for n in names:
        s = runs[n]["score"]
        out.append(f"- **{runs[n]['label']}**: {s['findings']} SCA findings, "
                   f"{len(s['outside_truth'])} not in the OSV snapshot, "
                   f"{len(s['missed'])} expected advisories missed; runtime "
                   f"{runs[n]['runtime_seconds']:.0f} s."
                   + (f" Coverage warnings: {'; '.join(s['coverage_warnings'])}" if s["coverage_warnings"] else ""))
    return out


def _provenance(results: dict) -> list[str]:
    out = ["### Provenance", "",
           f"Generated {results['generated']} by appsec-compose {results['appsec_compose']} "
           f"(commit `{results['appsec_compose_commit'][:12]}`) on {results['host']['platform']}, "
           f"Docker {results['host']['docker']}.", ""]
    engines: dict[str, str] = {}
    dbs: list[str] = []
    for suite_name, suite in results["suites"].items():
        for name, r in suite["runs"].items():
            engines.update(r["provenance"]["engines"])
            rec = r["provenance"].get("databases") or {}
            disk = r.get("db_dates_on_disk_after_run") or {}
            if rec or disk:
                used = {k: v for k, v in disk.items() if k in r["provenance"]["engines"]}
                dbs.append(f"- {suite_name}/{name}: findings.json provenance says "
                           f"`{rec or '{}'}`; cache after the run: `{used or '{}'}`")
    out += _table(["Engine", "Image (digest-pinned)"], [[k, f"`{v}`"] for k, v in sorted(engines.items())])
    if dbs:
        out += ["", "Vulnerability DB dates:", "", *dbs]
    return out


def render(results: dict) -> str:
    parts: list[str] = []
    s = results["suites"]
    if "sast" in s:
        parts += _sast(s["sast"]) + [""]
    if "secrets" in s:
        parts += _secrets(s["secrets"]) + [""]
    if "sca" in s:
        parts += _sca(s["sca"]) + [""]
    parts += _provenance(results)
    return "\n".join(parts)


def update_markdown(path: Path, results: dict) -> None:
    body = render(results)
    text = path.read_text() if path.exists() else f"# Benchmark results\n\n{BEGIN}\n{END}\n"
    if BEGIN not in text or END not in text:
        text = text.rstrip() + f"\n\n{BEGIN}\n{END}\n"
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    path.write_text(f"{head}{BEGIN}\n\n{body}\n\n{END}{tail}")
